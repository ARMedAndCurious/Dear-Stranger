import { Router } from 'express';
import * as notebooks from '../controllers/notebooks.js';
import * as advice from '../controllers/advice.js';
import rateLimit from 'express-rate-limit';
import { asyncHandler, requireAuth, validate } from '../middleware/index.js';
import { createNotebookSchema, updateNotebookSchema, adviceSchema, moderationActionSchema } from '../validation/schemas.js';
const router = Router();
const adviceLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many submissions. Please try again later.' } });
const translationLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many translation requests. Please try again later.' } });
router.get('/discover/list', asyncHandler(notebooks.explore));
router.get('/mine', requireAuth, asyncHandler(notebooks.mine));
router.post('/', requireAuth, validate(createNotebookSchema), asyncHandler(notebooks.create));
router.get('/manage/:id/advice', requireAuth, asyncHandler(advice.manage));
router.patch('/manage/:id/advice/:adviceId', requireAuth, validate(moderationActionSchema), asyncHandler(advice.decide));
router.post('/:slug/advice', adviceLimiter, validate(adviceSchema), asyncHandler(advice.submit));
router.get('/:slug/advice', (req, res, next) => req.query.language ? translationLimiter(req, res, next) : next(), asyncHandler(advice.pages));
router.patch('/:id', requireAuth, validate(updateNotebookSchema), asyncHandler(notebooks.update));
router.get('/:slug', asyncHandler(notebooks.view));
export default router;
